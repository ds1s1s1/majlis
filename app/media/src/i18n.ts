export type Key = keyof typeof STR.en;
export type Lang = 'ar' | 'en';

export function fmtLocaleDate(d: string | number | Date, lang: Lang, opts?: Intl.DateTimeFormatOptions) {
  return new Date(d).toLocaleDateString(lang === 'ar' ? 'ar-u-nu-latn' : 'en-US', opts);
}

export function fmtLocaleTime(d: string | number | Date, lang: Lang, opts?: Intl.DateTimeFormatOptions) {
  return new Date(d).toLocaleTimeString(lang === 'ar' ? 'ar-u-nu-latn' : 'en-US', opts);
}

export function fmtLocaleDateTime(d: string | number | Date, lang: Lang, opts?: Intl.DateTimeFormatOptions) {
  return new Date(d).toLocaleString(lang === 'ar' ? 'ar-u-nu-latn' : 'en-US', opts);
}

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s: string = STR[lang][key] ?? STR.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
